import assert from 'node:assert/strict';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { audioGain, detachTimelineAudio, resyncDetachedAudio, setAudioKeyframe, trackAudible, hasAudibleSpeech } from '../src/lib/timeline/audio';
import { commitTimeline, createTimelineClip, createTimelineTrack, splitTimelineClips, trimTimelineClip, moveTimelineClips, pasteTimelineClips, validateTimeline, type ReelTimeline, type TimelineAsset } from '../src/lib/timeline/model';
import { slipEdit } from '../src/lib/timeline/advanced-edits';
import { AudioClipControls } from '../src/components/caption-maker/AudioClipControls';

const video = createTimelineTrack('video');
const asset: TimelineAsset = { id: 'av_source', fileUrl: '/api/media/test.mp4', fileName: 'test.mp4', mediaType: 'video', hasAudio: true, durationMs: 12000 };
const source = { ...createTimelineClip(video, asset, 1000, 4000), sourceStartMs: 1000 };
const original: ReelTimeline = commitTimeline({ version: 1, enabled: true, fps: 25, tracks: [video], clips: [source], assets: [asset], captionSources: {}, markers: [] });
const snapshot = JSON.stringify(original);
let clip = setAudioKeyframe(source, 1000, 0, 25); clip = setAudioKeyframe(clip, 3000, 1, 25);
assert.equal(audioGain(clip, 1000), 0); assert.equal(audioGain(clip, 2000), 0.5); assert.equal(audioGain(clip, 3000), 1);
assert.equal(audioGain({ ...clip, muted: true }, 3000), 0);
assert.equal(audioGain({ ...source, audioFadeInMs: 1000, audioFadeOutMs: 1000 }, 1500), 0.5);
assert.equal(audioGain({ ...source, audioFadeInMs: 1000, audioFadeOutMs: 1000 }, 4500), 0.5);
assert.equal(audioGain({ ...source, fadeInMs: 1000 }, 1500), 0.5, 'Legacy fades stay audible');
assert.equal(audioGain({ ...source, fadeInMs: 1000, audioFadeInMs: 0 }, 1500), 1, 'Audio can override visual fades');
assert.equal(audioGain({ ...clip, volume: 2, audioKeyframes: [{ timeMs: 0, gain: 2 }] }, 2000), 2);
assert.equal(audioGain(source, 5000), 0);
assert.equal(setAudioKeyframe(clip, 3000, 0.4, 25).audioKeyframes!.length, 2, 'Replace same-frame keys');
const automated = { ...original, clips: [clip] };
const split = splitTimelineClips(automated, [clip.id], 3000);
assert.equal(audioGain(split.clips[1], 3500), audioGain(clip, 3500), 'Split retains the source curve');
assert.equal(audioGain(trimTimelineClip(automated, clip.id, 'left', 1000).clips[0], 3000), audioGain(clip, 3000));
assert.equal(audioGain(slipEdit(automated, [clip.id], 1000).clips[0], 2000), audioGain(clip, 3000));
const loop = { ...clip, loop: true, sourceStartMs: 0, audioKeyframes: [{ timeMs: 0, gain: 0 }, { timeMs: 1000, gain: 1 }] };
assert.equal(audioGain(loop, 3500, 2000), 0.5, 'Loop automation follows the source clock');
let detached = detachTimelineAudio(automated, clip.id);
const audio = detached.clips[1];
assert.equal(audio.sourceStartMs, source.sourceStartMs); assert.equal(audio.durationMs, source.durationMs); assert.equal(audio.startMs, source.startMs);
assert.equal(audio.linkId, detached.clips[0].linkId); assert.equal(detached.clips[0].muted, true); assert.equal(audio.muted, false);
assert.deepEqual(audio.audioKeyframes, clip.audioKeyframes);
assert.throws(() => detachTimelineAudio(detached, clip.id), /already detached/);
assert.equal(moveTimelineClips(detached, [clip.id], 1000).clips[1].startMs, audio.startMs + 1000);
const splitPair = splitTimelineClips(detached, [clip.id], 3000);
const rightAudio = splitPair.clips.find(c => c.detachedFromId && c.startMs === 3000)!;
assert.equal(splitPair.clips.find(c => c.id === rightAudio.detachedFromId)!.startMs, 3000);
const pasted = pasteTimelineClips(detached, detached.clips, 6000);
const copyAudio = pasted.clips.find(c => c.detachedFromId && c.startMs === 6000)!;
assert.equal(pasted.clips.find(c => c.id === copyAudio.detachedFromId)!.startMs, 6000);
detached = { ...detached, clips: detached.clips.map(c => c.id === audio.id ? { ...c, startMs: 2000, sourceStartMs: 2000, linkId: undefined } : c) };
assert.equal(resyncDetachedAudio(detached, audio.id).clips[1].startMs, source.startMs);
assert.equal(resyncDetachedAudio(detached, audio.id).clips[1].sourceStartMs, source.sourceStartMs);
assert.equal(trackAudible(detached, video), true);
const solo = { ...detached, tracks: detached.tracks.map(t => ({ ...t, solo: t.id === audio.trackId })) };
assert.equal(trackAudible(solo, video), false); assert.equal(trackAudible(solo, solo.tracks[1]), true);
assert.equal(trackAudible(solo, { ...solo.tracks[1], muted: true }), false);
assert.equal(trackAudible({ ...solo, tracks: solo.tracks.map(t => ({ ...t, solo: false })) }, video), true);
const locked = { ...original, tracks: [{ ...video, locked: true }] };
assert.throws(() => detachTimelineAudio(locked, source.id), /Unlock/);
assert.throws(() => detachTimelineAudio({ ...original, assets: [{ ...asset, hasAudio: false }] }, source.id), /confirmed audio/);
assert.ok(validateTimeline({ ...original, clips: [{ ...source, audioKeyframes: [{ timeMs: 100, gain: 3 }] }] }).length);
assert.ok(validateTimeline({ ...original, clips: [{ ...source, audioKeyframes: [{ timeMs: 100, gain: 1 }, { timeMs: 100, gain: 1 }] }] }).length);
assert.ok(validateTimeline({ ...original, clips: [{ ...source, audioFadeInMs: 5000 }] }).length);
assert.equal(JSON.stringify(original), snapshot, 'All source data remains immutable');
const plan = { timeline: original, durationMs: 5000, captionGroups: [], transcript: [{ id: 'w1', text: 'Voice', start: 1, end: 2 }] };
assert.equal(hasAudibleSpeech(plan, 1500), true);
assert.equal(hasAudibleSpeech({ ...plan, timeline: { ...original, clips: [{ ...source, muted: true }] } }, 1500), false, 'Muted speech must not duck music');
assert.equal(hasAudibleSpeech(plan, 4000), false);
const html = renderToStaticMarkup(React.createElement(AudioClipControls, { clip: source, disabled: false, onBegin() {}, onEdit() {}, onEnd() {}, onCancel() {} }));
assert.equal((html.match(/type="range"/g) || []).length, 3); assert.ok(html.includes('aria-label="Volume:'));
console.log('PASS: source-time keyframes, independent audio fades, solo/mute, detach/link/resync, split/copy references, limits and accessible clip handles');
