import assert from 'node:assert/strict';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { clipSourceTime, thumbnailTiles, thumbnailSampleTimes } from '../src/lib/timeline/thumbnails';
import { createTimelineClip, createTimelineTrack, type TimelineAsset } from '../src/lib/timeline/model';
import { VideoThumbnailStrip } from '../src/components/caption-maker/VideoThumbnailStrip';

const asset: TimelineAsset = { id: 'video', mediaType: 'video', fileName: 'video.mp4', fileUrl: '/api/files/video.mp4', durationMs: 100000 };
const track = createTimelineTrack('video');
const clip = { ...createTimelineClip(track, asset, 1000, 10000), sourceStartMs: 2000 };
const preview = { durationMs: 100000, thumbnails: ['a.jpg', 'b.jpg', 'c.jpg', 'd.jpg'], thumbnailTimesMs: [0, 10000, 50000, 99950] };
assert.equal(clipSourceTime(clip, 1000, 100000), 3000);
assert.equal(clipSourceTime(clip, -100, 100000), 2000);
assert.equal(clipSourceTime(clip, 50000, 100000), 11999);
assert.equal(clipSourceTime(clip, 1000, 0), 3000, 'Unknown metadata must not reset source-in to zero');
assert.equal(clipSourceTime({ ...clip, loop: true, sourceStartMs: 99000 }, 3000, 100000), 2000);
const low = thumbnailTiles(clip, 0.02, 80, 0, 20000, preview), high = thumbnailTiles(clip, 0.2, 80, 0, 20000, preview);
assert.ok(high.length > low.length); assert.equal(high[0].sourceTimeMs, 2000);
assert.ok(high.every(t => t.width > 0 && t.width <= 80));
const long = { ...clip, durationMs: 1000000 };
const scrolled = thumbnailTiles(long, 0.2, 80, 500000, 510000, preview);
assert.ok(scrolled.length < 40); assert.ok(scrolled[0].index > 100, 'Long clips continue rendering past the old 100-tile cutoff');
assert.ok(thumbnailTiles(long, 0.2, 80, 0, 1000000, preview).length <= 512);
assert.deepEqual(thumbnailTiles(clip, 0, 80, 0, 20000, preview), []);
assert.deepEqual(thumbnailTiles(clip, 0.2, 80, 0, 20000, { ...preview, thumbnails: [] }), []);
const end = thumbnailTiles({ ...clip, sourceStartMs: 99900, durationMs: 100 }, 0.2, 80, 0, 20000, preview);
assert.equal(end[0].src, 'd.jpg');
assert.equal(thumbnailSampleTimes(4000).length, 4); assert.equal(thumbnailSampleTimes(60000).length, 12); assert.equal(thumbnailSampleTimes(14400000).length, 24);
assert.equal(thumbnailSampleTimes(60000).at(-1), 59950); assert.deepEqual(thumbnailSampleTimes(NaN), []);
const html = renderToStaticMarkup(React.createElement(VideoThumbnailStrip, { clip, preview, pixelsPerMs: 0.2, height: 52, visibleStartMs: 0, visibleEndMs: 20000 }));
assert.ok(html.includes('loading="lazy"') && html.includes('decoding="async"') && html.includes('animate-pulse'));
assert.ok(html.includes('aria-hidden="true"'));
console.log('PASS: zoom density, bounded viewport tiles past index 100, source trims/loops/clamping, adaptive sample counts/times and lazy loading placeholders');
