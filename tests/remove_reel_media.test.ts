import assert from 'node:assert/strict';
import { createEmptyCaptionProject } from '../src/lib/caption-maker/sample-data';
import { removeReelMedia } from '../src/lib/caption-maker/remove-reel-media';
import { timelineFromProject } from '../src/lib/timeline/model';
const project = createEmptyCaptionProject();
project.audio = { id:'voice',fileName:'voice.wav',fileUrl:'/api/files/voice.wav',duration:4,fileSize:1,format:'wav' };
project.transcript = [{id:'w',text:'Hello',start:0,end:1}];
project.captionGroups = [{id:'g',text:'Hello',start:0,end:1,words:project.transcript}];
project.timeline = timelineFromProject(project);
const before=JSON.stringify(project);
const removed=removeReelMedia(project,'voice');
assert.equal(removed.audio,undefined);
assert.equal(removed.transcript.length,0);
assert.ok(!removed.timeline!.assets.some(asset=>asset.id==='voice'));
assert.equal(removed.timeline!.clips.length,0,'Linked captions are removed with voice');
assert.equal(JSON.stringify(project),before,'Undo snapshot remains intact');
const locked={...project,timeline:{...project.timeline,tracks:project.timeline.tracks.map(track=>({...track,locked:true}))}};
assert.throws(()=>removeReelMedia(locked,'voice'),/Unlock|locked/i);
project.mediaAssets=[{id:'image',fileName:'image.jpg',fileUrl:'/api/files/image.jpg',fileSize:1,width:100,height:100,format:'jpg',fitMode:'cover'}];
project.image=project.mediaAssets[0];
const imageRemoved=removeReelMedia(project,'image');
assert.equal(imageRemoved.image,undefined);
assert.equal(imageRemoved.mediaAssets!.length,0);
assert.equal(imageRemoved.audio!.id,'voice','Other media remains');
console.log('PASS: media deletion, linked clip removal, source references, undo immutability and locked-track protection');
