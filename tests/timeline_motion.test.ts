import assert from 'node:assert/strict';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { animationTime, applyMotionPreset, clipMotionStyle, easedProgress, motionValue, putMotionKeyframe, validMotion, motionPresets, type ClipMotion } from '../src/lib/timeline/motion';
import { createEmptyCaptionProject } from '../src/lib/caption-maker/sample-data';
import { createTimelineClip, createTimelineTrack, commitTimeline, splitTimelineClips, trimTimelineClip, pasteTimelineClips, validateTimeline, type ReelTimeline, type TimelineAsset } from '../src/lib/timeline/model';
import { rippleTrim, rollEdit, slideEdit, slipEdit } from '../src/lib/timeline/advanced-edits';
import { ClipMotionInspector } from '../src/components/caption-maker/ClipMotionInspector';
import { exportProjectAsJson, importProjectFromJson } from '../src/lib/caption-maker/project-storage';

const key = (timeMs: number, value: number) => ({ timeMs, value, easing: 'linear' as const });
let motion: ClipMotion = { channels: { x: [key(0, 0), key(4000, 100)], opacity: [key(0, 0), key(4000, 100)] } };
assert.equal(motionValue(motion.channels.x, 2000, 0), 50);
assert.equal(motionValue(motion.channels.x, -100, 0), 0);
assert.equal(motionValue(motion.channels.x, 5000, 0), 100);
assert.equal(easedProgress({ ...key(0, 0), easing: 'ease-in' }, 0.5), 0.25);
assert.equal(easedProgress({ ...key(0, 0), easing: 'ease-out' }, 0.5), 0.75);
assert.equal(easedProgress({ ...key(0, 0), easing: 'ease-in-out' }, 0.5), 0.5);
assert.ok(Math.abs(easedProgress({ ...key(0, 0), easing: 'bezier', bezier: [0.25, 0.25, 0.75, 0.75] }, 0.5) - 0.5) < 0.00001);
assert.equal(animationTime({ channels: { speed: [key(0, 2)] } }, 1000), 2000);
assert.ok(Math.abs(animationTime({ channels: { speed: [key(0, 1), key(2000, 3)] } }, 2000) - 4000) < 0.001);
assert.equal(animationTime(undefined, 1234), 1234);
assert.equal(animationTime({ offsetMs: 400, channels: {} }, 1000), 1400);
assert.equal(animationTime({ offsetMs: -400, channels: {} }, 100), 0);
for (const name of motionPresets) assert.equal(validMotion(applyMotionPreset(name, 4000)), true);
assert.equal(validMotion({ channels: { x: [key(10, 0), key(10, 5)] } }), false);
assert.equal(validMotion({ channels: { scale: [key(0, -1)] } }), false);
assert.equal(validMotion({ channels: { speed: [key(0, 0)] } }), false);
assert.equal(validMotion({ channels: { x: [{ ...key(0, 0), easing: 'bezier', bezier: [2, 0, 0, 1] }] } }), false);
assert.equal(validMotion({ channels: { unknown: [] } }), false);
motion = putMotionKeyframe(motion, 'x', key(4000, 100));
assert.equal(motion.channels.x!.length, 2, 'Same-time keys replace rather than duplicate');
const track = createTimelineTrack('video');
const asset: TimelineAsset = { id: 'motion_asset', fileName: 'motion.mp4', fileUrl: '/api/files/motion.mp4', mediaType: 'video', hasAudio: true, durationMs: 20000 };
const clip = { ...createTimelineClip(track, asset, 1000, 4000), sourceStartMs: 1000, motion };
const timeline: ReelTimeline = commitTimeline({ version: 1, enabled: true, fps: 25, tracks: [track], assets: [asset], clips: [clip], markers: [], captionSources: {} });
const snapshot = JSON.stringify(timeline);
assert.equal(clipMotionStyle(clip, 3000).opacity, 0.5);
assert.ok(clipMotionStyle(clip, 3000).transform!.includes('translate(50%'));
assert.deepEqual(clipMotionStyle({ ...clip, motion: undefined }, 3000), {}, 'Legacy clips acquire no identity transform/filter');
const trimmed = trimTimelineClip(timeline, clip.id, 'left', 400).clips[0];
assert.deepEqual(clipMotionStyle(trimmed, 3500), clipMotionStyle(clip, 3500));
const right = splitTimelineClips(timeline, [clip.id], 3000).clips[1];
assert.deepEqual(clipMotionStyle(right, 3500), clipMotionStyle(clip, 3500));
const rippled = rippleTrim(timeline, clip.id, 'left', 400).clips[0];
assert.deepEqual(clipMotionStyle(rippled, 2500), clipMotionStyle(clip, 2900));
const slipped = slipEdit(timeline, [clip.id], 400).clips[0];
assert.deepEqual(clipMotionStyle(slipped, 3000), clipMotionStyle(clip, 3000), 'Source slips do not move animation keys');
const pasted = pasteTimelineClips(timeline, [clip], 6000).clips[1];
assert.deepEqual(clipMotionStyle(pasted, 8000), clipMotionStyle(clip, 3000));
assert.notEqual(pasted.motion!.channels.x, clip.motion.channels.x, 'Pasted keys are independent');
const neighbors = { ...timeline, clips: [
  { ...createTimelineClip(track, asset, 0, 1000), id: 'left' }, clip,
  { ...createTimelineClip(track, asset, 5000, 2000), id: 'right', sourceStartMs: 2000, motion },
] };
const rolled = rollEdit(neighbors, clip.id, 'right', 400).clips.find(c => c.id === 'right')!;
assert.deepEqual(clipMotionStyle(rolled, 6000), clipMotionStyle(neighbors.clips[2], 6000));
const slide = slideEdit(neighbors, clip.id, 400).clips.find(c => c.id === 'right')!;
assert.deepEqual(clipMotionStyle(slide, 6000), clipMotionStyle(neighbors.clips[2], 6000));
const fast = { ...clip, motion: { ...motion, channels: { ...motion.channels, speed: [key(0, 2)] } } };
assert.deepEqual(clipMotionStyle(fast, 2000), clipMotionStyle(clip, 3000));
assert.equal(fast.sourceStartMs, clip.sourceStartMs); assert.equal(fast.durationMs, clip.durationMs);
assert.ok(validateTimeline({ ...timeline, clips: [{ ...clip, motion: { channels: { x: [key(0, NaN)] } } }] }).length);
const project = { ...createEmptyCaptionProject(), timeline };
const imported = importProjectFromJson(exportProjectAsJson(project));
assert.equal(imported.success, true); assert.deepEqual(imported.project!.timeline!.clips[0].motion, motion);
assert.equal(JSON.stringify(timeline), snapshot);
const markup = renderToStaticMarkup(React.createElement(ClipMotionInspector, { clip, currentMs: 2000, clipboard: motion, onCopy() {}, onChange() {} }));
assert.ok(markup.includes('Clip keyframe animation') && markup.includes('Copy keyframes') && markup.includes('animation graph'));
console.log('PASS: transform/effect curves, Bezier easing, animation velocity integration, presets, split/trim/roll/slide continuity, copy isolation, JSON persistence and legacy styles');
