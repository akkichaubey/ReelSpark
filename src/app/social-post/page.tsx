'use client';
import { accountCache } from '@/lib/account-cache';

// ReelSpark Smart Social Intelligence Studio — Updated 2026-10-22
import React, { useState, useEffect, useCallback } from 'react';
import Link from 'next/link';
import { useSearchParams } from 'next/navigation';
import {
  Sparkles,
  Copy,
  Check,
  RotateCw,
  Hash,
  Flame,
  MessageSquare,
  Share2,
  Info,
  Loader2,
  Film,
  ArrowLeft,
  FileText,
  Clock,
  ChevronDown,
  ChevronUp,
  Sliders,
  BookOpen,
  Users,
  ShieldCheck,
  CheckCircle2,
} from 'lucide-react';
import {
  SocialPostBundle,
  ContentTone,
  CaptionStyle,
  SocialPlatform,
} from '@/app/api/caption-maker/generate-social/route';
import { loadProjectFromLocalStorage } from '@/lib/caption-maker/project-storage';
import { useAuthStore } from '@/lib/use-auth-store';
import { AuthModal } from '@/components/AuthModal';
import { DashboardLayout } from '@/components/dashboard/DashboardLayout';
import { Suspense } from 'react';
import {
  SocialPlatformKey,
  PlatformContentType,
  PostValidationReport,
  SocialAccount,
} from '@/lib/social-intelligence/types';
import { SocialPlatformIcon } from '@/components/social-intelligence/SocialPlatformIcon';
import { SocialAccountsManager } from '@/components/social-intelligence/SocialAccountsManager';
import { PlatformGuidelinesViewer } from '@/components/social-intelligence/PlatformGuidelinesViewer';
import { PostValidationCard } from '@/components/social-intelligence/PostValidationCard';

type TabKey = 'generator' | 'accounts' | 'guidelines';

function SocialPostPageContent() {
  const searchParams = useSearchParams();
  const { user, isLoading: authLoading, openAuthModal, checkAuth } = useAuthStore();

  // The URL is the single source of truth for the selected page section.
  const tabParam = searchParams.get('tab') as string | null;
  const activeTab: TabKey =
    tabParam === 'preferences' || tabParam === 'accounts'
      ? 'accounts'
      : tabParam === 'guidelines'
        ? 'guidelines'
        : 'generator';

  useEffect(() => {
    checkAuth();
  }, [checkAuth]);

  // Core content states
  const [transcript, setTranscript] = useState<string>('');
  const [clipTitle, setClipTitle] = useState<string>('Viral Reel Clip');
  const [clipDuration, setClipDuration] = useState<number>(30);
  const [sourceClipId, setSourceClipId] = useState<string | null>(null);
  const [showSourceTranscript, setShowSourceTranscript] = useState<boolean>(false);

  // Configuration options
  const [language, setLanguage] = useState<'en' | 'hi' | 'hinglish'>('en');
  const [tone, setTone] = useState<ContentTone>('motivational');
  const [platform, setPlatform] = useState<SocialPlatformKey | 'all'>('instagram');
  const [contentType, setContentType] = useState<PlatformContentType>('reel');
  const [includeLinks, setIncludeLinks] = useState<boolean>(true);
  const [captionStyle, setCaptionStyle] = useState<CaptionStyle>('curiosity');

  // Generation & display states
  const [isLoading, setIsLoading] = useState<boolean>(false);
  const [bundle, setBundle] = useState<SocialPostBundle | null>(null);
  const [selectedVariationIdx, setSelectedVariationIdx] = useState<number>(0);
  const [editedTitle, setEditedTitle] = useState<string>('');
  const [editedText, setEditedText] = useState<string>('');
  const [copiedKey, setCopiedKey] = useState<string | null>(null);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);
  const [hasAutoGenerated, setHasAutoGenerated] = useState<boolean>(false);

  // Validation state
  const [validationReport, setValidationReport] = useState<PostValidationReport | null>(null);
  const [validating, setValidating] = useState<boolean>(false);

  // User Accounts (for fast client-side hints)
  const [userAccounts, setUserAccounts] = useState<SocialAccount[]>([]);

  // Fetch user accounts once
  useEffect(() => {
    const fetchAccounts = async () => {
      try {
        const res = await fetch('/api/social-accounts');
        const data = await res.json();
        if (data.success) {
          setUserAccounts(data.accounts || []);
        }
      } catch (e) {
        // silently fallback
      }
    };
    fetchAccounts();
  }, []);

  // Load context from LocalStorage or URL parameters
  useEffect(() => {
    if (typeof window === 'undefined') return;

    const params = new URLSearchParams(window.location.search);
    const paramLang = params.get('lang') as 'en' | 'hi' | 'hinglish' | null;
    const paramTitle = params.get('title');
    const paramDuration = params.get('duration');
    const paramClipId = params.get('clipId');
    const paramTranscript = params.get('transcript');

    let initialTranscript = '';
    let initialTitle = 'Viral Reel Clip';
    let initialDuration = 30;
    let initialLang: 'en' | 'hi' | 'hinglish' = paramLang || 'en';

    // 1. Check if temporary clip session was stored from ClipCard
    try {
      const storedContextRaw = accountCache.getItem('reel_social_post_context');
      if (storedContextRaw) {
        const storedContext = JSON.parse(storedContextRaw);
        if (storedContext?.transcript) {
          initialTranscript = storedContext.transcript;
          if (storedContext.title) initialTitle = storedContext.title;
          if (storedContext.duration) initialDuration = storedContext.duration;
          if (storedContext.language) initialLang = storedContext.language;
          if (storedContext.clipId) setSourceClipId(storedContext.clipId);
        }
      }
    } catch (e) {
      console.warn('Failed to parse reel_social_post_context:', e);
    }

    // 2. Fall back to current project in LocalStorage (from Caption Maker)
    if (!initialTranscript) {
      const currentProject = loadProjectFromLocalStorage();
      if (currentProject) {
        if (currentProject.title) initialTitle = currentProject.title;
        if (currentProject.audio?.duration) initialDuration = currentProject.audio.duration;
        if (currentProject.preferredLanguage) initialLang = currentProject.preferredLanguage;
        if (currentProject.sourceClipId) setSourceClipId(currentProject.sourceClipId);

        if (initialLang === 'hi' && currentProject.rawTranscriptHindi) {
          initialTranscript = currentProject.rawTranscriptHindi;
        } else if (initialLang === 'hinglish' && currentProject.rawTranscriptHinglish) {
          initialTranscript = currentProject.rawTranscriptHinglish;
        } else if (currentProject.rawTranscriptEnglish) {
          initialTranscript = currentProject.rawTranscriptEnglish;
        } else if (currentProject.transcript && currentProject.transcript.length > 0) {
          initialTranscript = currentProject.transcript.map((w) => w.text).join(' ');
        }
      }
    }

    // 3. Fall back to URL parameter overrides
    if (paramTranscript) initialTranscript = paramTranscript;
    if (paramTitle) initialTitle = paramTitle;
    if (paramDuration) initialDuration = Number(paramDuration) || 30;
    if (paramClipId) setSourceClipId(paramClipId);

    // Apply resolved values
    setTranscript(initialTranscript);
    setClipTitle(initialTitle);
    setClipDuration(initialDuration);
    setLanguage(initialLang);
  }, []);

  // Fetch or regenerate social post bundle
  const handleGenerate = useCallback(
    async (
      targetLang = language,
      targetTone = tone,
      targetPlatform = platform,
      targetContentType = contentType,
      targetIncludeLinks = includeLinks,
      targetCaptionStyle = captionStyle,
      textToUse = transcript
    ) => {
      if (!textToUse || textToUse.trim().length === 0) {
        setErrorMessage('No transcript text available. Please enter or load a transcript.');
        return;
      }

      setIsLoading(true);
      setErrorMessage(null);

      try {
        const res = await fetch('/api/caption-maker/generate-social', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            transcript: textToUse,
            title: clipTitle,
            duration: clipDuration,
            language: targetLang,
            tone: targetTone,
            platform: targetPlatform,
            contentType: targetContentType,
            includeLinks: targetIncludeLinks,
            captionStyle: targetCaptionStyle,
          }),
        });

        const data = await res.json();
        if (!res.ok || !data.success) {
          throw new Error(data.error || 'Failed to generate social media post copy');
        }

        setBundle(data.bundle);
        setSelectedVariationIdx(0);
        setEditedTitle(data.bundle.postTitle || '');
        const firstVar = data.bundle.variations?.[0];
        const newText = firstVar ? firstVar.fullText : '';
        setEditedText(newText);

        if (data.validationReport) {
          setValidationReport(data.validationReport);
        }
      } catch (err: any) {
        console.error('Error generating social post:', err);
        setErrorMessage(err?.message || 'Failed to generate copy. Please try again.');
      } finally {
        setIsLoading(false);
      }
    },
    [language, tone, platform, contentType, includeLinks, captionStyle, transcript, clipTitle, clipDuration]
  );

  // Trigger auto-generation once transcript is loaded and no bundle exists
  useEffect(() => {
    if (transcript && transcript.trim().length > 0 && !bundle && !isLoading && !hasAutoGenerated) {
      setHasAutoGenerated(true);
      handleGenerate(language, tone, platform, contentType, includeLinks, captionStyle, transcript);
    }
  }, [transcript, bundle, isLoading, hasAutoGenerated, handleGenerate, language, tone, platform, contentType, includeLinks, captionStyle]);

  // Real-time debounced post validation as editedText changes
  useEffect(() => {
    if (!editedText || editedText.trim().length === 0) return;

    const timer = setTimeout(async () => {
      try {
        setValidating(true);
        const res = await fetch('/api/caption-maker/validate-post', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            title: editedTitle,
            fullText: editedText,
            platform: platform === 'all' ? 'instagram' : platform,
            contentType,
          }),
        });
        const data = await res.json();
        if (data.success && data.report) {
          setValidationReport(data.report);
        }
      } catch (e) {
        console.warn('Real-time validation error:', e);
      } finally {
        setValidating(false);
      }
    }, 350);

    return () => clearTimeout(timer);
  }, [editedTitle, editedText, platform, contentType]);

  // Update edited text when changing variation tab
  const handleSelectVariation = (idx: number) => {
    setSelectedVariationIdx(idx);
    if (bundle?.variations?.[idx]) {
      setEditedText(bundle.variations[idx].fullText);
    }
  };

  // Copy helper with visual feedback
  const handleCopy = (text: string, key: string) => {
    if (!text) return;
    navigator.clipboard.writeText(text);
    setCopiedKey(key);
    setTimeout(() => {
      setCopiedKey(null);
    }, 2500);
  };

  if (!authLoading && !user) {
    return (
      <div className="min-h-screen bg-zinc-950 flex flex-col text-white">
        <header className="h-14 border-b border-zinc-800 bg-zinc-900/90 px-4 sm:px-6 flex items-center justify-between shrink-0 z-30 sticky top-0 backdrop-blur-md">
          <Link href="/" className="flex items-center gap-2 hover:opacity-90 transition-opacity">
            <div className="w-8 h-8 rounded-lg bg-amber-400 flex items-center justify-center text-zinc-950 font-black shadow-md shadow-amber-400/20">
              <Share2 className="w-4 h-4 text-zinc-950" />
            </div>
            <div>
              <span className="font-bold text-sm tracking-tight text-white flex items-center gap-1.5">
                AI Social Intelligence Studio
                <span className="text-[10px] font-mono px-1.5 py-0.5 rounded bg-amber-500/10 text-amber-400 border border-amber-500/30">
                  Pro
                </span>
              </span>
            </div>
          </Link>
          <button
            onClick={() => openAuthModal('login')}
            className="px-4 py-1.5 rounded-xl bg-amber-400 hover:bg-amber-300 text-zinc-950 font-bold text-xs cursor-pointer shadow-sm transition-all"
          >
            Sign In / Register
          </button>
        </header>

        <main className="flex-1 flex flex-col items-center justify-center p-8 text-center relative overflow-hidden">
          <div className="max-w-md space-y-4 relative z-10">
            <div className="w-12 h-12 rounded-2xl bg-amber-500/10 border border-amber-500/20 text-amber-400 flex items-center justify-center mx-auto shadow-lg shadow-amber-500/10">
              <Share2 className="w-6 h-6" />
            </div>
            <h2 className="text-2xl font-bold">Sign In to Smart Social Intelligence</h2>
            <p className="text-xs text-zinc-400 leading-relaxed">
              Generate platform-aware social copy with deterministic link insertion, platform guidelines, and real-time quality scoring.
            </p>
            <div className="pt-2">
              <button
                onClick={() => openAuthModal('login')}
                className="w-full py-3 rounded-xl bg-white hover:bg-zinc-200 text-zinc-950 font-bold text-xs cursor-pointer shadow-lg shadow-white/10 transition-all hover:scale-[1.01] active:scale-[0.99]"
              >
                Sign In to Continue
              </button>
            </div>
          </div>
        </main>
        <AuthModal />
      </div>
    );
  }

  // Count active accounts excluding target platform
  const targetExcludedCount = userAccounts.filter(
    (a) => a.enabled && (platform === 'all' || a.platform !== platform)
  ).length;

  return (
    <DashboardLayout
      title="Smart Social Intelligence Studio"
      subtitle="Platform-Aware Copywriting, Link Engine & Quality Scoring"
      breadcrumbs={[
        { label: 'Dashboard', href: '/' },
        { label: 'Social Intelligence', href: '/social-post' },
        { label: activeTab === 'generator' ? 'Copy Generator' : activeTab === 'accounts' ? 'Social Accounts' : 'Platform Specs' },
      ]}
      headerActions={
        <Link
          href="/reel-maker"
          className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg border border-zinc-700/60 bg-zinc-800/80 hover:bg-zinc-700 text-zinc-300 text-xs font-semibold transition-all cursor-pointer shadow-sm active:scale-95"
          title="Return to AI Reel Maker"
        >
          <ArrowLeft className="w-3.5 h-3.5" />
          <span className="hidden sm:inline">Back to Caption Studio</span>
        </Link>
      }
    >
      <div className="space-y-6 max-w-6xl mx-auto">
        {/* Tab 1: AI Generator */}
        {activeTab === 'generator' && (
          <div className="space-y-6">
            {/* Informative Banner */}
            <div className="px-4 sm:px-6 py-2.5 rounded-2xl bg-amber-500/10 border border-amber-500/20 flex items-center justify-between gap-3 text-xs text-amber-200">
              <div className="flex items-center gap-2.5">
                <Info className="w-4 h-4 text-amber-400 shrink-0" />
                <span>
                  <strong>Platform-Aware Intelligence:</strong> Captions are automatically formatted to match character limits and hashtag policies for your chosen platform. Target platform account link is cleanly excluded by default.
                </span>
              </div>
              <span className="hidden lg:inline-block text-[10px] font-mono uppercase bg-amber-500/20 text-amber-300 px-2 py-0.5 rounded border border-amber-500/30 shrink-0">
                Instagram • YouTube • Threads • Facebook
              </span>
            </div>

            {/* Active Clip Header & Source Transcript Drawer */}
            <div className="p-4 rounded-2xl bg-zinc-900/80 border border-zinc-800/80 shadow-md space-y-3">
              <div className="flex flex-wrap items-center justify-between gap-3">
                <div className="flex items-center gap-2.5">
                  <div className="w-8 h-8 rounded-xl bg-amber-400 flex items-center justify-center text-zinc-950 font-bold shadow-md shadow-amber-400/20">
                    <Share2 className="w-4 h-4" />
                  </div>
                  <div>
                    <h2 className="text-sm sm:text-base font-bold text-white flex items-center gap-2">
                      <span>{clipTitle}</span>
                      {sourceClipId && (
                        <span className="text-[10px] bg-zinc-800 text-zinc-400 font-mono px-2 py-0.5 rounded">
                          Clip #{sourceClipId.slice(0, 8)}
                        </span>
                      )}
                    </h2>
                    <div className="flex items-center gap-2 text-xs text-zinc-400">
                      <span className="flex items-center gap-1 font-mono">
                        <Clock className="w-3 h-3 text-zinc-500" />
                        {clipDuration ? `${Math.round(clipDuration)}s duration` : 'Selected clip'}
                      </span>
                      <span>•</span>
                      <span>Speech transcript bridge from Clip Finder &amp; Caption Studio</span>
                    </div>
                  </div>
                </div>

                {/* Toggle Source Transcript Drawer */}
                <button
                  type="button"
                  onClick={() => setShowSourceTranscript(!showSourceTranscript)}
                  className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-zinc-800 hover:bg-zinc-700 text-zinc-300 text-xs font-semibold border border-zinc-700 transition-colors cursor-pointer"
                >
                  <FileText className="w-3.5 h-3.5 text-amber-400" />
                  <span>{showSourceTranscript ? 'Hide Source Transcript' : 'View Source Transcript'}</span>
                  {showSourceTranscript ? (
                    <ChevronUp className="w-3.5 h-3.5" />
                  ) : (
                    <ChevronDown className="w-3.5 h-3.5" />
                  )}
                </button>
              </div>

              {/* Collapsible Source Transcript Accordion */}
              {showSourceTranscript && (
                <div className="pt-3 border-t border-zinc-800 space-y-2 animate-in fade-in duration-200">
                  <div className="flex items-center justify-between">
                    <label className="text-xs font-semibold text-zinc-400">
                      Clip Speech Transcript (Editable):
                    </label>
                    <span className="text-[11px] text-zinc-500 font-mono">
                      {transcript.trim() ? `${transcript.trim().split(/\s+/).length} words` : '0 words'}
                    </span>
                  </div>
                  <textarea
                    rows={3}
                    value={transcript}
                    onChange={(e) => setTranscript(e.target.value)}
                    placeholder="Paste or edit the spoken speech transcript here to generate social copy..."
                    className="w-full bg-zinc-950 border border-zinc-800 rounded-xl p-3 text-xs text-zinc-300 font-mono leading-relaxed focus:outline-none focus:border-amber-400 resize-none shadow-inner"
                  />
                </div>
              )}
            </div>

            {/* Smart Intelligence Controls Bar */}
            <div className="p-4 sm:p-5 rounded-2xl bg-zinc-900/90 border border-zinc-800 space-y-4 shadow-md">
              {/* Row 1: Target Platform Selector with Visual Icons */}
              <div className="space-y-2">
                <div className="flex items-center justify-between">
                  <span className="text-xs text-zinc-300 font-semibold uppercase tracking-wider">
                    Target Platform:
                  </span>
                  <span className="text-[11px] text-zinc-500">
                    Self-link exclusion active for target
                  </span>
                </div>

                <div className="grid grid-cols-2 sm:grid-cols-5 gap-2">
                  {[
                    { id: 'instagram', label: 'Instagram' },
                    { id: 'youtube', label: 'YouTube' },
                    { id: 'threads', label: 'Threads' },
                    { id: 'facebook', label: 'Facebook' },
                    { id: 'all', label: 'All Platforms' },
                  ].map((p) => {
                    const isSelected = platform === p.id;
                    return (
                      <button
                        key={p.id}
                        type="button"
                        onClick={() => {
                          const newPlatform = p.id as SocialPlatformKey | 'all';
                          setPlatform(newPlatform);
                          handleGenerate(language, tone, newPlatform, contentType, includeLinks, captionStyle);
                        }}
                        className={`flex items-center justify-center gap-2 p-2.5 rounded-xl border text-xs font-medium transition-all ${
                          isSelected
                            ? 'bg-amber-400 text-zinc-950 border-amber-400 shadow-md shadow-amber-400/20 font-bold'
                            : 'bg-zinc-950/80 text-zinc-400 hover:text-white border-zinc-800 hover:border-zinc-700'
                        }`}
                      >
                        {p.id !== 'all' && (
                          <SocialPlatformIcon platform={p.id as SocialPlatformKey} size="sm" />
                        )}
                        <span>{p.label}</span>
                      </button>
                    );
                  })}
                </div>
              </div>

              {/* Row 2: Secondary Options (Content Type, Tone, Language, Style, Links Toggle) */}
              <div className="flex flex-wrap items-center justify-between gap-4 pt-3 border-t border-zinc-800/80">
                <div className="flex flex-wrap items-center gap-3">
                  {/* Content Type */}
                  <div className="flex items-center gap-1.5">
                    <span className="text-xs text-zinc-400 font-medium">Type:</span>
                    <select
                      value={contentType}
                      onChange={(e) => {
                        const newType = e.target.value as PlatformContentType;
                        setContentType(newType);
                        handleGenerate(language, tone, platform, newType, includeLinks, captionStyle);
                      }}
                      className="bg-zinc-950 border border-zinc-700 text-xs text-zinc-200 rounded-lg px-2.5 py-1.5 focus:border-amber-400 focus:outline-none capitalize cursor-pointer shadow-sm"
                    >
                      <option value="reel">🎬 Reel / Short</option>
                      <option value="post">📝 Standard Post</option>
                      <option value="story">⚡ Story</option>
                      <option value="video">📽️ Video Post</option>
                    </select>
                  </div>

                  {/* Tone */}
                  <div className="flex items-center gap-1.5">
                    <span className="text-xs text-zinc-400 font-medium">Tone:</span>
                    <select
                      value={tone}
                      onChange={(e) => {
                        const newTone = e.target.value as ContentTone;
                        setTone(newTone);
                        handleGenerate(language, newTone, platform, contentType, includeLinks, captionStyle);
                      }}
                      className="bg-zinc-950 border border-zinc-700 text-xs text-zinc-200 rounded-lg px-2.5 py-1.5 focus:border-amber-400 focus:outline-none capitalize cursor-pointer shadow-sm"
                    >
                      <option value="motivational">🔥 Motivational</option>
                      <option value="educational">💡 Educational</option>
                      <option value="storytelling">📖 Storytelling</option>
                      <option value="funny">😂 Funny / Viral</option>
                      <option value="emotional">❤️ Emotional / Deep</option>
                      <option value="professional">💼 Professional</option>
                    </select>
                  </div>

                  {/* Language */}
                  <div className="flex items-center gap-1.5">
                    <span className="text-xs text-zinc-400 font-medium">Language:</span>
                    <div className="flex items-center bg-zinc-950 p-0.5 rounded-lg border border-zinc-700 shadow-sm">
                      {[
                        { id: 'en', label: 'English' },
                        { id: 'hi', label: 'हिन्दी' },
                        { id: 'hinglish', label: 'Hinglish' },
                      ].map((l) => (
                        <button
                          key={l.id}
                          type="button"
                          onClick={() => {
                            const newLang = l.id as 'en' | 'hi' | 'hinglish';
                            setLanguage(newLang);
                            handleGenerate(newLang, tone, platform, contentType, includeLinks, captionStyle);
                          }}
                          className={`px-2.5 py-1 rounded-md text-xs font-semibold transition-all cursor-pointer ${
                            language === l.id
                              ? 'bg-amber-400 text-zinc-950 shadow-sm font-bold'
                              : 'text-zinc-400 hover:text-white'
                          }`}
                        >
                          {l.label}
                        </button>
                      ))}
                    </div>
                  </div>

                  {/* Caption Style */}
                  <div className="flex items-center gap-1.5">
                    <label htmlFor="caption-style" className="text-xs text-zinc-400 font-medium">
                      Style:
                    </label>
                    <select
                      id="caption-style"
                      value={captionStyle}
                      onChange={(e) => {
                        const newStyle = e.target.value as CaptionStyle;
                        setCaptionStyle(newStyle);
                        handleGenerate(language, tone, platform, contentType, includeLinks, newStyle);
                      }}
                      className="max-w-44 bg-zinc-950 border border-zinc-700 text-xs text-zinc-200 rounded-lg px-2.5 py-1.5 focus:border-amber-400 focus:outline-none cursor-pointer shadow-sm"
                      title="Sets the hook, post structure, and call to action for the generated copy"
                    >
                      <option value="curiosity">🔎 Curiosity Hook</option>
                      <option value="story">📖 Personal Story</option>
                      <option value="quick_value">✅ Quick Value List</option>
                      <option value="hinglish">🗣️ Relatable Hinglish</option>
                      <option value="debate">💬 Debate Question</option>
                      <option value="trend">⚡ Trend Reaction</option>
                      <option value="educational">🎓 Educational Proof</option>
                      <option value="comment_dm">✉️ Comment-to-DM CTA</option>
                    </select>
                  </div>

                  {/* Include Links Toggle */}
                  <label className="flex items-center gap-2 cursor-pointer bg-zinc-950 border border-zinc-800 px-2.5 py-1.5 rounded-lg">
                    <input
                      type="checkbox"
                      checked={includeLinks}
                      onChange={(e) => {
                        const checked = e.target.checked;
                        setIncludeLinks(checked);
                        handleGenerate(language, tone, platform, contentType, checked, captionStyle);
                      }}
                      className="w-3.5 h-3.5 rounded border-zinc-700 accent-amber-400 cursor-pointer"
                    />
                    <span className="text-xs text-zinc-300">
                      Include Social Links ({targetExcludedCount})
                    </span>
                  </label>
                </div>

                {/* Regenerate Button */}
                <button
                  type="button"
                  onClick={() => handleGenerate()}
                  disabled={isLoading || !transcript.trim()}
                  className="flex items-center gap-1.5 px-4 py-2 bg-gradient-to-r from-amber-400 to-amber-500 hover:from-amber-300 hover:to-amber-400 text-zinc-950 font-bold rounded-xl text-xs transition-all disabled:opacity-50 cursor-pointer shadow-md shadow-amber-400/20 active:scale-95"
                >
                  <RotateCw className={`w-3.5 h-3.5 ${isLoading ? 'animate-spin' : ''}`} />
                  <span>Regenerate Copy</span>
                </button>
              </div>
            </div>

            {/* Content Body Area */}
            <div className="p-5 sm:p-6 rounded-2xl bg-zinc-900/80 border border-zinc-800/80 shadow-xl space-y-6">
              {isLoading ? (
                <div className="py-24 flex flex-col items-center justify-center space-y-3 text-center">
                  <Loader2 className="w-9 h-9 text-amber-400 animate-spin" />
                  <p className="text-sm font-semibold text-zinc-200">
                    Generating platform-aware social post copy...
                  </p>
                  <p className="text-xs text-zinc-500 max-w-md">
                    Applying {platform} length constraints, deterministic social link filtering, and hashtag rules.
                  </p>
                </div>
              ) : errorMessage ? (
                <div className="p-6 bg-rose-500/10 border border-rose-500/30 rounded-2xl text-center space-y-3">
                  <p className="text-xs sm:text-sm text-rose-300 font-medium">{errorMessage}</p>
                  <button
                    type="button"
                    onClick={() => handleGenerate()}
                    className="px-4 py-2 bg-rose-500/20 text-rose-300 rounded-xl text-xs font-semibold hover:bg-rose-500/30 transition-colors shadow-sm"
                  >
                    Try Again
                  </button>
                </div>
              ) : bundle ? (
                <>
                  {/* 0. AI-generated title, editable before publishing */}
                  <div className="p-4 bg-zinc-950/70 border border-zinc-800 rounded-xl space-y-2.5">
                    <div className="flex items-center justify-between gap-3">
                      <label htmlFor="platform-post-title" className="text-xs font-bold text-zinc-300 flex items-center gap-1.5">
                        <FileText className="w-4 h-4 text-amber-400" />
                        <span>{platform === 'youtube' ? 'YouTube Title' : 'AI-Generated Post Title'}</span>
                      </label>
                      <span className={`text-[11px] font-mono ${editedTitle.length > (platform === 'youtube' ? 100 : 90) ? 'text-rose-400' : 'text-zinc-500'}`}>
                        {editedTitle.length}/{platform === 'youtube' ? 100 : 90}
                      </span>
                    </div>
                    <div className="flex gap-2">
                      <input
                        id="platform-post-title"
                        value={editedTitle}
                        onChange={(e) => setEditedTitle(e.target.value)}
                        maxLength={platform === 'youtube' ? 100 : 90}
                        className="min-w-0 flex-1 bg-zinc-900 border border-zinc-700/80 rounded-lg px-3 py-2 text-xs sm:text-sm text-zinc-100 focus:outline-none focus:border-amber-400"
                        placeholder="AI-generated platform title"
                      />
                      <button
                        type="button"
                        onClick={() => handleCopy(editedTitle, 'post_title')}
                        className="shrink-0 px-3 py-2 rounded-lg bg-zinc-800 text-xs font-semibold text-zinc-300 hover:text-white hover:bg-zinc-700 transition-colors"
                        aria-label="Copy post title"
                      >
                        {copiedKey === 'post_title' ? <Check className="w-4 h-4 text-emerald-400" /> : <Copy className="w-4 h-4" />}
                      </button>
                    </div>
                    <p className="text-[11px] text-zinc-500">
                      Generated for {platform === 'all' ? 'Instagram-style universal social copy' : platform}; you can edit it before copying.
                    </p>
                  </div>

                  {/* 1. Viral Opening Hooks Cards */}
                  <div className="space-y-2.5">
                    <label className="text-xs font-bold text-zinc-300 flex items-center justify-between">
                      <span className="flex items-center gap-1.5">
                        <Flame className="w-4 h-4 text-amber-400" />
                        <span>Viral Opening Hooks (First 3 Seconds)</span>
                      </span>
                      <span className="text-[11px] text-zinc-500 font-normal">
                        Click any hook card to copy instantly
                      </span>
                    </label>
                    <div className="grid grid-cols-1 md:grid-cols-3 gap-3">
                      {bundle.hooks.map((hook, hIdx) => {
                        const isCopied = copiedKey === `hook_${hIdx}`;
                        return (
                          <div
                            key={hIdx}
                            onClick={() => handleCopy(hook, `hook_${hIdx}`)}
                            className="p-3.5 bg-zinc-950/80 hover:bg-zinc-800/80 border border-zinc-800 hover:border-amber-500/50 rounded-xl cursor-pointer transition-all flex flex-col justify-between group shadow-sm"
                          >
                            <p className="text-xs text-zinc-200 leading-snug font-medium mb-3">
                              &quot;{hook}&quot;
                            </p>
                            <div className="flex items-center justify-between text-[11px] text-zinc-500 group-hover:text-amber-400">
                              <span>Hook #{hIdx + 1}</span>
                              <span className="flex items-center gap-1 font-semibold">
                                {isCopied ? (
                                  <>
                                    <Check className="w-3.5 h-3.5 text-emerald-400" />
                                    <span className="text-emerald-400">Copied!</span>
                                  </>
                                ) : (
                                  <>
                                    <Copy className="w-3.5 h-3.5" />
                                    <span>Copy Hook</span>
                                  </>
                                )}
                              </span>
                            </div>
                          </div>
                        );
                      })}
                    </div>
                  </div>

                  {/* 2. Variation Tabs for Complete Social Post */}
                  <div className="space-y-2.5 pt-2">
                    <div className="flex flex-wrap items-center justify-between gap-2">
                      <label className="text-xs font-bold text-zinc-300 flex items-center gap-1.5">
                        <MessageSquare className="w-4 h-4 text-amber-400" />
                        <span>Complete Post Copy (Ready to Paste)</span>
                      </label>

                      {/* Variation Switcher */}
                      <div className="flex items-center gap-1 bg-zinc-950 p-1 rounded-xl border border-zinc-800 text-xs">
                        {bundle.variations.map((v, vIdx) => (
                          <button
                            key={vIdx}
                            type="button"
                            onClick={() => handleSelectVariation(vIdx)}
                            className={`px-3 py-1 rounded-lg font-semibold transition-all cursor-pointer ${
                              selectedVariationIdx === vIdx
                                ? 'bg-amber-400 text-zinc-950 shadow-sm font-bold'
                                : 'text-zinc-400 hover:text-white'
                            }`}
                          >
                            {v.title}
                          </button>
                        ))}
                      </div>
                    </div>

                    {/* Editable Text Area for Selected Variation */}
                    <div className="relative">
                      <textarea
                        rows={10}
                        value={editedText}
                        onChange={(e) => setEditedText(e.target.value)}
                        className="w-full bg-zinc-950 border border-zinc-700/80 rounded-xl p-4 text-xs sm:text-sm text-zinc-200 font-sans leading-relaxed focus:outline-none focus:border-amber-400 resize-none shadow-inner"
                        placeholder="Social media caption text..."
                      />

                      {/* Floating Copy Action on Textarea */}
                      <div className="absolute top-3.5 right-3.5 flex items-center gap-1.5">
                        <button
                          type="button"
                          onClick={() => handleCopy(editedText, 'full_post')}
                          className={`flex items-center gap-1.5 px-3.5 py-1.5 rounded-lg text-xs font-bold transition-all cursor-pointer shadow-md ${
                            copiedKey === 'full_post'
                              ? 'bg-emerald-500 text-black'
                              : 'bg-gradient-to-r from-amber-400 to-amber-500 hover:from-amber-300 hover:to-amber-400 text-zinc-950 font-bold shadow-amber-400/20 active:scale-95'
                          }`}
                        >
                          {copiedKey === 'full_post' ? (
                            <>
                              <Check className="w-3.5 h-3.5 stroke-[3]" />
                              <span>Copied Full Post!</span>
                            </>
                          ) : (
                            <>
                              <Copy className="w-3.5 h-3.5" />
                              <span>Copy Post</span>
                            </>
                          )}
                        </button>
                      </div>
                    </div>
                  </div>

                  {/* 3. Live Smart Post Validation Card */}
                  <PostValidationCard
                    report={validationReport}
                    targetPlatform={platform === 'all' ? 'instagram' : platform}
                    loading={validating}
                  />

                  {/* 4. Hashtags Cloud Section */}
                  <div className="p-4 bg-zinc-950/70 border border-zinc-800 rounded-xl space-y-2.5">
                    <div className="flex items-center justify-between">
                      <span className="text-xs font-semibold text-zinc-300 flex items-center gap-1.5">
                        <Hash className="w-4 h-4 text-amber-400" />
                        <span>Target Hashtags ({bundle.hashtags.length})</span>
                      </span>
                      <button
                        type="button"
                        onClick={() => handleCopy(bundle.hashtags.join(' '), 'hashtags_only')}
                        className="flex items-center gap-1 text-xs text-amber-300 hover:text-amber-200 font-semibold cursor-pointer"
                      >
                        {copiedKey === 'hashtags_only' ? (
                          <>
                            <Check className="w-3.5 h-3.5 text-emerald-400" />
                            <span className="text-emerald-400">Hashtags Copied!</span>
                          </>
                        ) : (
                          <>
                            <Copy className="w-3.5 h-3.5" />
                            <span>Copy All Hashtags</span>
                          </>
                        )}
                      </button>
                    </div>
                    <div className="flex flex-wrap gap-1.5">
                      {bundle.hashtags.map((tag, tIdx) => (
                        <span
                          key={tIdx}
                          onClick={() => handleCopy(tag, `tag_${tIdx}`)}
                          className="px-2.5 py-1 rounded-md text-xs font-mono bg-zinc-900 hover:bg-zinc-800 text-zinc-400 hover:text-amber-300 border border-zinc-800 hover:border-zinc-700 cursor-pointer transition-colors"
                          title="Click to copy this hashtag"
                        >
                          {tag}
                        </span>
                      ))}
                    </div>
                  </div>
                </>
              ) : (
                <div className="py-16 flex flex-col items-center justify-center space-y-3 text-center">
                  <FileText className="w-10 h-10 text-zinc-600" />
                  <p className="text-sm font-semibold text-zinc-300">
                    No transcript loaded yet
                  </p>
                  <p className="text-xs text-zinc-500 max-w-sm">
                    Paste your speech transcript above or select a clip from the Clip Finder or Caption Studio to generate platform-aware social copy.
                  </p>
                </div>
              )}
            </div>

            {/* Bottom Actions Footer */}
            <div className="p-4 rounded-2xl bg-zinc-900/90 border border-zinc-800 flex flex-wrap items-center justify-between gap-3 shadow-md">
              <span className="text-xs text-zinc-500 font-mono">
                {clipDuration ? `Clip Duration: ${Math.round(clipDuration)}s` : 'Selected Clip'}
              </span>
              <div className="flex items-center gap-2.5">
                <Link
                  href="/reel-maker"
                  className="px-4 py-2 rounded-xl text-xs font-semibold text-zinc-400 hover:text-white bg-zinc-800/80 hover:bg-zinc-800 transition-colors cursor-pointer"
                >
                  Back to Reel Maker
                </Link>
                {bundle && (
                  <button
                    type="button"
                    onClick={() => handleCopy(editedText, 'full_post')}
                    className="flex items-center gap-1.5 px-5 py-2 bg-gradient-to-r from-amber-400 to-amber-500 hover:from-amber-300 hover:to-amber-400 text-zinc-950 font-bold rounded-xl text-xs transition-all shadow-md shadow-amber-400/20 active:scale-95 cursor-pointer"
                  >
                    {copiedKey === 'full_post' ? (
                      <>
                        <Check className="w-3.5 h-3.5 stroke-[3]" />
                        <span>Copied!</span>
                      </>
                    ) : (
                      <>
                        <Copy className="w-3.5 h-3.5" />
                        <span>Copy Full Post</span>
                      </>
                    )}
                  </button>
                )}
              </div>
            </div>
          </div>
        )}

        {/* Tab 2: Social Accounts Manager */}
        {activeTab === 'accounts' && (
          <div className="p-5 sm:p-6 rounded-2xl bg-zinc-900/80 border border-zinc-800/80 shadow-xl w-full">
            <SocialAccountsManager />
          </div>
        )}

        {/* Tab 3: Platform Guidelines */}
        {activeTab === 'guidelines' && (
          <div className="p-5 sm:p-6 rounded-2xl bg-zinc-900/80 border border-zinc-800/80 shadow-xl">
            <PlatformGuidelinesViewer />
          </div>
        )}
      </div>
    </DashboardLayout>
  );
}

